#!/usr/bin/env python3
"""Generate a dry-run protocol skeleton + EXECUTION_LOG template for a skill.

Usage:
  python3 new-protocol.py <skill_name> <output_dir>
     [-g <golden_dir>] [-w <whitelist_item>] ... [-a <extra_assert>] ...

Prompts for nothing; writes:
  <output_dir>/<skill_name>_protocol.md  (from protocol_template.md)
  <output_dir>/EXECUTION_LOG.template.md
Prints the path to write. Python 3.6 compatible.
"""
import os
import re
import sys
import datetime

TEMPLATE = """# {skill} Dry-Run Protocol (generated by skill-eval-loop)

## 1. Goal
Validate that the {skill} skill's documentation independently produces a
runnable result: fresh subagents (no context) execute end-to-end; the
orchestrator checks artifacts, attributes defects, fixes the skill, freezes
defects as regression assertions. Rounds iterate until convergence.

## 2. Roles
| Role | Responsibility |
|---|---|
| Subagent (fresh) | Execute + record EXECUTION_LOG.md. Forbidden: skill-doc analysis, reading golden |
| Orchestrator | Verify artifacts, attribute (doc/execution/environment), fix skill, drive rounds |
| User | Review fixes, confirm convergence |

## 3. Subtask sequence
| # | Subtask | Deliverable | Verify |
|---|---|---|---|
| T1 | Phase 1 | | L1 |
| T2 | Phase 2 | | L1/L2 |
| T3 | Phase 3 | | L2/L3 |
| T4 | Run & iterate | | L4 (only pass definition) |

## 4. Whitelist (not defects)
- {whitelist}

## 5. Convergence criteria (ALL)
1. Whitelist-external diff = 0 (semantic asserts, not byte equality)
2. L1-L4 all green (run_evals one command)
3. Fresh agent completes with ZERO orchestrator artifact edits
4. User confirmation

## 6. Round table
| Round | Skill fixes | External diff | L1-L4 | Conclusion |
|---|---|---|---|---|
| R1 | — (baseline) | | | |
"""

EXEC_TEMPLATE = """## Task: <T# name>
## Steps (commands + output summaries, in order)
## Obstacles (verbatim error text, one per entry)
## Assumptions (choices when doc was vague + rationale)
## Status (complete/partial/stuck)
"""


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(2)
    skill = sys.argv[1]
    outdir = sys.argv[2]
    golden = None
    whitelist = []
    i = 3
    while i < len(sys.argv):
        a = sys.argv[i]
        if a == '-g' and i + 1 < len(sys.argv):
            golden = sys.argv[i + 1]
            i += 2
        elif a == '-w' and i + 1 < len(sys.argv):
            whitelist.append(sys.argv[i + 1])
            i += 2
        else:
            i += 1
    os.makedirs(outdir, exist_ok=True)
    wl = ('; '.join(whitelist) if whitelist
          else 'naming diffs, comments/formatting, build artifacts, timestamps, '
               'legal alternative physical values')
    proto = TEMPLATE.format(skill=skill, whitelist=wl)
    p_path = os.path.join(outdir, '%s_protocol.md' % skill)
    with open(p_path, 'w', encoding='utf-8') as f:
        f.write(proto)
    e_path = os.path.join(outdir, 'EXECUTION_LOG.template.md')
    with open(e_path, 'w', encoding='utf-8') as f:
        f.write(EXEC_TEMPLATE)
    print('wrote:')
    print('  ' + p_path)
    print('  ' + e_path)
    print('Golden dir: %s' % (golden or '(none set — add explicit forbidden paths in subagent prompts)'))


if __name__ == '__main__':
    main()
